-- MAIN WEATHER TABLE (1:1 with planet, optional 1:1 with moon)
-- =====================================================================
CREATE TABLE ud.planetary_weather (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planet_id BIGINT,
    moon_id BIGINT,

    -- Atmospheric Structure
    scale_height_km DOUBLE PRECISION,
    tropopause_altitude_km DOUBLE PRECISION,
    total_atmosphere_height_km DOUBLE PRECISION,
    sky_color VARCHAR(50),
    sky_color_description VARCHAR(200),
    twilight_duration_minutes DOUBLE PRECISION,

    -- Temperature & Climate
    day_night_temp_range_k DOUBLE PRECISION,
    seasonal_temp_amplitude_k DOUBLE PRECISION,
    season_description VARCHAR(300),
    thermal_inertia_class VARCHAR(30),
    mean_equatorial_temp_k DOUBLE PRECISION,
    mean_polar_temp_k DOUBLE PRECISION,

    -- Wind & Circulation
    circulation_pattern VARCHAR(50),
    circulation_cell_count INTEGER,
    jet_stream_count INTEGER,
    jet_stream_speed_ms DOUBLE PRECISION,
    mean_surface_wind_speed_ms DOUBLE PRECISION,
    max_gust_speed_ms DOUBLE PRECISION,
    wind_intensity VARCHAR(30),
    has_super_rotation BOOLEAN DEFAULT FALSE,
    super_rotation_factor DOUBLE PRECISION,

    -- Clouds
    cloud_coverage_percent DOUBLE PRECISION,
    cloud_coverage_class VARCHAR(30),
    primary_cloud_composition VARCHAR(100),

    -- Precipitation
    has_precipitation BOOLEAN DEFAULT FALSE,
    primary_precipitation_type VARCHAR(50),
    precipitation_frequency VARCHAR(30),
    precipitation_reaches_surface BOOLEAN DEFAULT TRUE,

    -- Storms
    storm_frequency VARCHAR(30),
    typical_storm_wind_speed_ms DOUBLE PRECISION,
    has_dust_storms BOOLEAN DEFAULT FALSE,
    dust_storms_can_be_global BOOLEAN DEFAULT FALSE,
    has_lightning BOOLEAN DEFAULT FALSE,
    lightning_type VARCHAR(50),

    -- Tidal Effects
    tidal_range_meters DOUBLE PRECISION,
    dominant_tidal_period_hours DOUBLE PRECISION,
    atmospheric_tidal_effect VARCHAR(200),

    -- Gas Giant Specific
    number_of_bands INTEGER,
    internal_heat_flux_wm2 DOUBLE PRECISION,
    internal_to_stellar_ratio DOUBLE PRECISION,
    has_great_dark_spot BOOLEAN DEFAULT FALSE,

    -- Visual / Narrative
    daytime_sky_description VARCHAR(500),
    nighttime_sky_description VARCHAR(500),
    sunset_description VARCHAR(300),
    outdoor_exposure_rating VARCHAR(50),
    survival_time_description VARCHAR(200),

    -- Weather Summary
    weather_summary VARCHAR(1000),
    weather_severity VARCHAR(30),

    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    modified_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    -- Constraints
    CONSTRAINT chk_weather_scale_height_positive CHECK (scale_height_km IS NULL OR scale_height_km > 0),
    CONSTRAINT chk_weather_cloud_coverage_range CHECK (cloud_coverage_percent IS NULL OR (cloud_coverage_percent >= 0 AND cloud_coverage_percent <= 100)),
    CONSTRAINT chk_weather_day_night_range_positive CHECK (day_night_temp_range_k IS NULL OR day_night_temp_range_k >= 0),
    CONSTRAINT chk_weather_seasonal_amp_positive CHECK (seasonal_temp_amplitude_k IS NULL OR seasonal_temp_amplitude_k >= 0),
    CONSTRAINT chk_weather_wind_speed_positive CHECK (mean_surface_wind_speed_ms IS NULL OR mean_surface_wind_speed_ms >= 0),
    CONSTRAINT chk_weather_tidal_range_positive CHECK (tidal_range_meters IS NULL OR tidal_range_meters >= 0)
);

ALTER TABLE ud.planetary_weather OWNER TO starcreator_dev;

COMMENT ON TABLE ud.planetary_weather IS 'Weather and climate assessment for planets and moons with atmospheres. Calculated post-generation from orbital, atmospheric, and geological data.';
COMMENT ON COLUMN ud.planetary_weather.planet_id IS 'FK to planet. Mutually exclusive with moon_id.';

COMMENT ON COLUMN ud.planetary_weather.precipitation_frequency IS 'How often precipitation occurs: NEVER, RARE, OCCASIONAL, FREQUENT, CONTINUOUS';
COMMENT ON COLUMN ud.planetary_weather.storm_frequency IS 'Storm system frequency: RARE, OCCASIONAL, FREQUENT, CONSTANT';
